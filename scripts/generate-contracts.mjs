import { readFileSync, writeFileSync } from 'node:fs';

const TARGET = 'src/api/contracts.generated.ts';

const SPECS = [
  { ts: 'EmployeeDto', rust: 'Employee', file: 'src-tauri/src/services/db/model.rs' },
  { ts: 'LdapOrgConfigDto', rust: 'LdapOrgConfig', file: 'src-tauri/src/services/config/model.rs' },
  { ts: 'LdapOrgInput', rust: 'LdapOrgInput', file: 'src-tauri/src/services/config/model.rs' },
  { ts: 'OrgGroupDto', rust: 'OrgGroup', file: 'src-tauri/src/services/config/model.rs' },
  { ts: 'SearchPageDto', rust: 'SearchPage', file: 'src-tauri/src/services/db/model.rs' },
  { ts: 'SearchParamsDto', rust: 'SearchParams', file: 'src-tauri/src/services/db/model.rs' },
  { ts: 'OrgSyncStateDto', rust: 'OrgSyncState', file: 'src-tauri/src/services/sync.rs' },
  { ts: 'SyncStatusDto', rust: 'SyncStatus', file: 'src-tauri/src/services/sync.rs' },
  { ts: 'ConnectionTestDto', rust: 'ConnectionTest', file: 'src-tauri/src/services/ldap/model.rs' },
  { ts: 'VCardInputDto', rust: 'VCardInput', file: 'src-tauri/src/services/vcard.rs' },
];

const TYPE_MAP = {
  Employee: 'EmployeeDto',
  OrgSyncState: 'OrgSyncStateDto',
};

function camelCase(value) {
  return value.replace(/_([a-z0-9])/g, (_, char) => char.toUpperCase());
}

function tsType(rustType) {
  const type = rustType.trim();
  const optional = type.match(/^Option<(.+)>$/);
  if (optional) return `${tsType(optional[1])} | null`;
  const vector = type.match(/^Vec<(.+)>$/);
  if (vector) return `${tsType(vector[1])}[]`;
  if (type === 'String' || type === '&str') return 'string';
  if (/^(u|i)(8|16|32|64)$/.test(type)) return 'number';
  if (type === 'bool') return 'boolean';
  if (TYPE_MAP[type]) return TYPE_MAP[type];
  throw new Error(`unsupported Rust type: ${rustType}`);
}

function structFields(source, name) {
  const match = source.match(new RegExp(`pub struct ${name} \\{([\\s\\S]*?)\\n\\}`));
  if (!match) throw new Error(`struct ${name} not found`);
  const fields = [];
  let renamed = null;
  for (const raw of match[1].split('\n')) {
    const line = raw.trim();
    const rename = line.match(/#\[serde\(rename\s*=\s*"([^"]+)"\)\]/);
    if (rename) {
      renamed = rename[1];
      continue;
    }
    const field = line.match(/^pub\s+([a-z0-9_]+)\s*:\s*(.+),$/);
    if (!field) continue;
    fields.push({
      name: renamed ?? camelCase(field[1]),
      type: tsType(field[2]),
    });
    renamed = null;
  }
  if (fields.length === 0) throw new Error(`${name} has no fields`);
  return fields;
}

const blocks = SPECS.map((spec) => {
  const source = readFileSync(spec.file, 'utf8');
  const fields = structFields(source, spec.rust);
  return `// ${spec.ts} from ${spec.file} (${spec.rust})
export interface ${spec.ts} {
${fields.map((field) => `  ${field.name}: ${field.type};`).join('\n')}
}`;
});

const generated = `// @generated by scripts/generate-contracts.mjs - do not edit by hand.
// Sources are the serde structs listed below.

${blocks.join('\n\n')}
`;

const expected = process.argv.includes('--check');
const current = (() => {
  try {
    return readFileSync(TARGET, 'utf8');
  } catch {
    return null;
  }
})();

if (expected) {
  if (current !== generated) {
    console.error(`${TARGET} is stale; run npm run generate:contracts`);
    process.exit(1);
  }
  console.log(`generated contracts are current: ${TARGET} (${SPECS.length} interfaces)`);
} else {
  writeFileSync(TARGET, generated);
  console.log(`wrote ${TARGET} (${SPECS.length} interfaces)`);
}
