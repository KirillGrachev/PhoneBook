//! Configuration model: organizations, UI preferences, save request.
//!
//! Passwords do not live in the model: instead there is a `hasPassword` flag - the secret
//! remains in the system store (see [`super::store::ConfigStore`]).

use serde::{Deserialize, Serialize};

pub(super) fn default_theme() -> String {
    "system".to_string()
}

pub(super) fn default_language() -> String {
    "en".to_string()
}

fn default_sync_interval() -> u32 {
    24
}

fn default_ldap_connect_timeout() -> u32 {
    15
}

fn default_ldap_operation_timeout() -> u32 {
    30
}

const fn default_true() -> bool {
    true
}

/// Connection parameters for one organization's catalog.
///
/// This structure simultaneously describes what the frontend sees:
/// instead of a password it has the `hasPassword` flag - the secret remains in the keyring.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LdapOrgConfig {
    pub organization: String,
    pub ldap_url: String,
    pub base_dn: String,
    #[serde(default)]
    pub bind_dn: Option<String>,
    /// StartTLS over `ldap://` (AD: port 389 + STARTTLS).
    #[serde(default)]
    pub use_start_tls: bool,
    /// Do not verify the server certificate (only for ldaps/StartTLS
    /// with self-signed certificates in the internal network).
    #[serde(default)]
    pub allow_invalid_tls: bool,
    /// Authentication under the current Windows session (Kerberos/NTLM, SASL GSSAPI).
    /// No password is needed.
    #[serde(default = "default_true")]
    pub use_integrated_auth: bool,
    /// Computed on load: whether a password exists in the system store.
    #[serde(default)]
    pub has_password: bool,
}

/// Organization input when saving configuration (without the password).
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LdapOrgInput {
    pub organization: String,
    pub ldap_url: String,
    pub base_dn: String,
    #[serde(default)]
    pub bind_dn: Option<String>,
    #[serde(default)]
    pub use_start_tls: bool,
    #[serde(default)]
    pub allow_invalid_tls: bool,
    #[serde(default = "default_true")]
    pub use_integrated_auth: bool,
}

/// Organization group: several AD `company` filters combined
/// under one name.
///
/// The group is used in two places:
/// * the organization filter in the global version - the group replaces it in the dropdown
///   organizations absorbed by it (one item instead of many);
/// * the "KMAruda" tab in the non-global version - the group marked in settings
///   defines the set of organizations whose accounts are considered in the list.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OrgGroup {
    /// Stable identifier (generated by the frontend, UUID).
    pub id: String,
    /// Union filter display name.
    pub name: String,
    /// Organization names (AD `company` values / filter names).
    pub orgs: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct AppConfig {
    #[serde(default = "default_theme")]
    pub theme: String,
    #[serde(default = "default_language")]
    pub language: String,
    /// "Global version": show all organizations of the holding and a filter by them.
    #[serde(default)]
    pub global_mode: bool,
    #[serde(default)]
    pub saved_contact_ids: Vec<String>,
    #[serde(default)]
    pub ldap_configs: Vec<LdapOrgConfig>,
    /// Demo mode: data comes from local mocks; AD is not queried.
    #[serde(default)]
    pub test_mode: bool,
    #[serde(default = "default_true")]
    pub animations_enabled: bool,
    /// Show contact photos as avatars; when false, letter initials are used.
    #[serde(default = "default_true")]
    pub show_avatars: bool,
    /// Automatic background sync period, hours.
    #[serde(default = "default_sync_interval")]
    pub sync_interval_hours: u32,
    /// LDAP TCP/TLS handshake timeout, seconds.
    #[serde(default = "default_ldap_connect_timeout")]
    pub ldap_connect_timeout_secs: u32,
    /// LDAP operation/page timeout, seconds.
    #[serde(default = "default_ldap_operation_timeout")]
    pub ldap_operation_timeout_secs: u32,
    /// Hide "empty" accounts (without email, mobile, and work phone):
    /// system/service records do not clutter the results.
    #[serde(default = "default_true")]
    pub hide_empty_contacts: bool,
    /// Local email substitutions for contacts without the mail attribute.
    #[serde(default)]
    pub email_overrides: std::collections::HashMap<String, String>,
    /// Named organization groups (union filters).
    #[serde(default)]
    pub org_groups: Vec<OrgGroup>,
    /// Group for the "KMAruda" tab (non-global version): `None` -
    /// inherited behavior (organization of the first AD connection).
    #[serde(default)]
    pub enterprise_group_id: Option<String>,
    /// Legacy single external phone book path. New saves also populate
    /// `external_phonebook_paths`; kept for older configs and older clients.
    #[serde(default)]
    pub external_phonebook_path: Option<String>,
    /// External phone book files (Yealink IPPhoneBook, XML). Each file is
    /// imported as a separate directory source.
    #[serde(default)]
    pub external_phonebook_paths: Vec<String>,
    /// Load external phone book files into the directory.
    #[serde(default)]
    pub external_phonebook_enabled: bool,
    /// Per-file automatic refresh interval in hours; `0`/absent means manual.
    #[serde(default)]
    pub external_phonebook_intervals: std::collections::HashMap<String, u32>,
    /// Drop Yealink entries that duplicate an AD employee by full name + any
    /// contact/attribute. `true` — hide duplicates, `false` — keep them.
    #[serde(default = "default_true")]
    pub external_hide_ad_duplicates: bool,
    /// Application version that wrote the config (diagnostics).
    #[serde(default)]
    pub version: Option<String>,
    /// Whether the embedded managed profile is active. Computed on load;
    /// not written to disk.
    #[serde(default, skip_serializing_if = "is_false")]
    pub managed: bool,
    /// Embedded profile name (diagnostics; not written to disk).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub managed_profile: Option<String>,
    /// Embedded profile revision (diagnostics; not written to disk).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub managed_revision: Option<u32>,
}

fn is_false(value: &bool) -> bool {
    !*value
}

impl Default for AppConfig {
    fn default() -> Self {
        Self {
            theme: default_theme(),
            language: default_language(),
            global_mode: false,
            saved_contact_ids: Vec::new(),
            ldap_configs: Vec::new(),
            test_mode: false,
            animations_enabled: true,
            show_avatars: true,
            sync_interval_hours: default_sync_interval(),
            ldap_connect_timeout_secs: default_ldap_connect_timeout(),
            ldap_operation_timeout_secs: default_ldap_operation_timeout(),
            hide_empty_contacts: true,
            email_overrides: std::collections::HashMap::new(),
            org_groups: Vec::new(),
            enterprise_group_id: None,
            external_phonebook_path: None,
            external_phonebook_paths: Vec::new(),
            external_phonebook_enabled: false,
            external_phonebook_intervals: std::collections::HashMap::new(),
            external_hide_ad_duplicates: true,
            version: Some(env!("CARGO_PKG_VERSION").to_string()),
            managed: false,
            managed_profile: None,
            managed_revision: None,
        }
    }
}

